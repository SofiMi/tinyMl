#!/usr/bin/env python3
"""Verify the pinned TinyStories release and generate firmware tokenizer tables."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / 'components/esp32ai'
ASSETS = COMPONENT / 'assets'
PINS = {
    'model.bin': ('1d8326c05c383ccfa615f5455575802817cb453dbc7ab28875d41a9dbb45477e', 14912348),
    'tokenizer.json': ('4e28163669f2249af31a528a54fc25064dcbd0a34edbfa7bedb16d2d600ec7ae', 1788896),
}


def prepare(output):
    output.mkdir(parents=True, exist_ok=True)
    metadata = json.loads((ASSETS / 'metadata.json').read_text())
    for name, (sha, size) in PINS.items():
        data = (ASSETS / name).read_bytes()
        if len(data) != size or hashlib.sha256(data).hexdigest() != sha:
            raise SystemExit(f'{name}: checksum/size mismatch; restore the pinned release')
        if metadata['files'][name]['sha256'] != sha or metadata['files'][name]['bytes'] != size:
            raise SystemExit(f'{name}: release metadata disagrees with pins')
    spec = importlib.util.spec_from_file_location(
        'encoder_generator', COMPONENT / 'upstream/tools/generate_tokenizer_header.py')
    encoder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(encoder)
    source = (ASSETS / 'tokenizer.json').read_bytes()
    config = json.loads(source)
    # The upstream encoder does not match added tokens. EOS is output-only in
    # this console; reject its literal spelling on input, and pack ordinary BPE.
    assert config['added_tokens'] == [{
        'id': 0, 'content': '<|endoftext|>', 'single_word': False, 'lstrip': False,
        'rstrip': False, 'normalized': False, 'special': True}]
    config['added_tokens'] = []
    asset, count, _, _ = encoder.build_asset(json.dumps(config).encode())
    asset = asset[:24] + hashlib.sha256(source).digest()[:28] + asset[52:]
    (output / 'tokenizer_encoder.h').write_text(encoder.render(asset))
    (output / 'tokenizer.btk').write_bytes(asset)
    # Preserve raw byte pieces, including partial UTF-8 sequences. EOS emits no text.
    byte_map = {symbol: byte for byte, symbol in encoder.BYTE_SYMBOLS.items()}
    vocab = config['model']['vocab']
    by_id = sorted(vocab, key=vocab.get)
    blob = bytearray()
    offsets = [0]
    for i, symbol in enumerate(by_id):
        if i:
            blob.extend(byte_map[c] for c in symbol)
        offsets.append(len(blob))
    def array(name, kind, values):
        rows = [','.join(map(str, values[i:i+20])) for i in range(0, len(values), 20)]
        return f'static const {kind} {name}[] = {{\n' + ',\n'.join(rows) + '\n};\n'
    (output / 'vocab.h').write_text(
        '// Generated by tools/prepare_esp32ai.py; do not edit.\n#pragma once\n'
        f'#define VOCAB_N {count}\n#define EOS_ID 0\n' +
        array('VOCAB_BLOB', 'unsigned char', blob) +
        array('VOCAB_OFF', 'unsigned int', offsets))
    print(f'Verified TinyStories release; generated {count} token entries in {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    prepare(parser.parse_args().out)
